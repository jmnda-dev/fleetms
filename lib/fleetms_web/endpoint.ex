defmodule FleetmsWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :fleetms

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_fleetms_key",
    signing_salt: "685V+aeu",
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :fleetms,
    gzip: not code_reloading?,
    only: FleetmsWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # User-uploaded files served by the Local storage adapter, from priv/uploads —
  # outside priv/static on purpose, so the asset pipeline above never sees them
  # (the static allowlist's dev `raise_on_missing_only` check would otherwise trip
  # on them, and `phx.digest` would fingerprint them). A no-op when uploads are
  # served from object storage instead.
  plug Plug.Static,
    at: "/uploads",
    from: Application.compile_env(:fleetms, :uploads_dir, {:fleetms, "priv/uploads"}),
    gzip: false

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug AshPhoenix.Plug.CheckCodegenStatus
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :fleetms
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library(),
    # Keep the raw body for webhook routes so provider signatures can be verified.
    body_reader: {FleetmsWeb.CacheBodyReader, :read_body, []}

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options

  # Serve Prometheus metrics at /metrics (see Fleetms.PromEx). This endpoint is
  # unauthenticated, so keep it internal-only / firewalled in production
  # (e.g. block /metrics at the reverse proxy, or scrape it over a private network).
  plug PromEx.Plug, prom_ex_module: Fleetms.PromEx

  plug FleetmsWeb.Router
end
