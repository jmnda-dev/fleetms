defmodule Fleetms.Inspections.InspectionSchedule do
  @moduledoc """
  A recurring inspection: form F should be filled against vehicle V every N days,
  optionally assigned to a member.

  The schedule is the *rule*; the concrete "do this by date X" items it produces are
  `InspectionAssignment` rows, generated by a daily Oban job
  (`Fleetms.Inspections.ScheduleRunner`). The runner keeps exactly one open
  assignment per active schedule, so missed periods roll into a single overdue item
  rather than piling up. Submitting a matching inspection closes the open assignment
  and the next one is generated on the following run.

  Cadence is a plain day interval (`interval_days`: 1 = daily, 7 = weekly, …) from a
  `start_date` anchor. Mileage-based cadence and group/driver targeting are future
  extensions; v1 targets one vehicle per schedule.
  """
  use Ash.Resource,
    otp_app: :fleetms,
    domain: Fleetms.Inspections,
    data_layer: AshPostgres.DataLayer,
    authorizers: [Ash.Policy.Authorizer],
    extensions: [Fleetms.Permissions.Dsl, AshOban, AshJsonApi.Resource]

  import Fleetms.Permissions, only: [has_permission: 1]

  alias Fleetms.Inspections

  @writable_attrs [:name, :interval_days, :start_date, :active]

  postgres do
    table "inspection_schedules"
    repo Fleetms.Repo

    references do
      reference :inspection_form, on_delete: :delete
      reference :vehicle, on_delete: :delete
      reference :assigned_to, on_delete: :nilify
    end
  end

  permissions do
    permission :view_inspection_schedules,
      action: :read,
      label: "View Inspection Schedules",
      group: "Inspections"

    permission :create_inspection_schedule,
      action: :create,
      label: "Create Inspection Schedule",
      group: "Inspections"

    permission :update_inspection_schedule,
      action: :update,
      label: "Update Inspection Schedule",
      group: "Inspections"

    permission :delete_inspection_schedule,
      action: :destroy,
      label: "Delete Inspection Schedule",
      group: "Inspections"
  end

  oban do
    # Run once per organization; the tenant (an `org_<id>` schema string) is what
    # `Fleetms.Repo.all_tenants/0` returns and is set on the action.
    list_tenants fn -> Fleetms.Repo.all_tenants() end

    scheduled_actions do
      # Every morning, top up each org's due inspection assignments — one open
      # assignment per active schedule.
      schedule :generate_due_assignments, "0 6 * * *" do
        action :generate_due_assignments
        queue :inspection_schedules
        worker_module_name Fleetms.Inspections.InspectionSchedule.Workers.GenerateDueAssignments
      end
    end
  end

  json_api do
    type "inspection-schedule"
  end

  actions do
    defaults [:read, :destroy]
    default_accept []

    # Run per organization by AshOban: ensure each active schedule has an open
    # assignment. Returns how many assignments were created.
    action :generate_due_assignments, :integer do
      run fn _input, context ->
        {:ok, Inspections.ScheduleRunner.generate_for_tenant(context.tenant)}
      end
    end

    read :get_by_id do
      get_by :id
      prepare build(load: [vehicle: [:name], inspection_form: [:title]])
    end

    read :list do
      argument :vehicle_id, :uuid
      argument :inspection_form_id, :uuid
      argument :search_query, :string, default: ""
      argument :filters, :map, default: %{}

      argument :sort_by, :atom do
        constraints one_of: [:interval_days, :open_assignment_count, :inserted_at]
        default :inserted_at
      end

      argument :sort_order, :atom do
        constraints one_of: [:asc, :desc]
        default :desc
      end

      filter expr(
               if(is_nil(^arg(:vehicle_id)), do: true, else: vehicle_id == ^arg(:vehicle_id)) and
                 if(is_nil(^arg(:inspection_form_id)),
                   do: true,
                   else: inspection_form_id == ^arg(:inspection_form_id)
                 )
             )

      pagination offset?: true, countable: true, default_limit: 20, max_page_size: 100

      prepare Fleetms.Inspections.InspectionSchedule.Preparations.ListInspectionSchedules
    end

    create :create do
      primary? true
      accept @writable_attrs

      argument :inspection_form_id, :uuid, allow_nil?: false
      argument :vehicle_id, :uuid, allow_nil?: false
      argument :assigned_to_id, :uuid

      change manage_relationship(:inspection_form_id, :inspection_form, type: :append_and_remove)

      change manage_relationship(:vehicle_id, :vehicle, type: :append_and_remove)
      change manage_relationship(:assigned_to_id, :assigned_to, type: :append_and_remove)
    end

    update :update do
      primary? true
      require_atomic? false
      accept @writable_attrs

      argument :assigned_to_id, :uuid

      change manage_relationship(:assigned_to_id, :assigned_to, type: :append_and_remove)
    end
  end

  policies do
    bypass actor_attribute_equals(:is_super_admin, true) do
      authorize_if always()
    end

    policy action_type(:read) do
      authorize_if has_permission(:view_inspection_schedules)
    end

    policy action_type(:create) do
      authorize_if has_permission(:create_inspection_schedule)
    end

    policy action_type(:update) do
      authorize_if has_permission(:update_inspection_schedule)
    end

    policy action_type(:destroy) do
      authorize_if has_permission(:delete_inspection_schedule)
    end

    # System generator action, invoked only by the AshOban scheduled job (no actor).
    policy action(:generate_due_assignments) do
      authorize_if always()
    end
  end

  multitenancy do
    strategy :context
  end

  attributes do
    uuid_primary_key :id

    attribute :name, :string do
      public? true
      constraints max_length: 120
      description "Optional label, e.g. \"Daily pre-trip\"."
    end

    attribute :interval_days, :integer do
      public? true
      allow_nil? false
      default 1
      constraints min: 1, max: 3650
      description "Cadence in days: 1 = daily, 7 = weekly, and so on."
    end

    attribute :start_date, :date do
      public? true
      allow_nil? false
      default &Date.utc_today/0
      description "Anchor date; the first assignment is due on this date."
    end

    attribute :active, :boolean do
      public? true
      allow_nil? false
      default true
      description "Inactive schedules keep their history but generate nothing new."
    end

    timestamps()
  end

  relationships do
    belongs_to :inspection_form, Fleetms.Inspections.InspectionForm do
      allow_nil? false
      public? true
      attribute_writable? true
    end

    belongs_to :vehicle, Fleetms.VehicleManagement.Vehicle do
      allow_nil? false
      public? true
      attribute_writable? true
    end

    belongs_to :assigned_to, Fleetms.Accounts.User do
      domain Fleetms.Accounts
      allow_nil? true
      public? true
      attribute_writable? true
      description "The member responsible for filling the inspection, if any."
    end

    has_many :assignments, Fleetms.Inspections.InspectionAssignment do
      destination_attribute :schedule_id
    end
  end

  aggregates do
    count :open_assignment_count, :assignments do
      filter expr(is_nil(completed_at))
    end
  end

  identities do
    identity :unique_vehicle_form, [:vehicle_id, :inspection_form_id]
  end
end
