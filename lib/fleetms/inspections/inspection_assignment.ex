defmodule Fleetms.Inspections.InspectionAssignment do
  @moduledoc """
  One concrete "fill inspection form F on vehicle V by `due_on`" item, produced by
  an `InspectionSchedule`.

  Assignments are generated by the schedule's daily Oban job and closed when a
  matching inspection is submitted (`inspection_id` + `completed_at` set). How it
  stands — `:pending` / `:overdue` / `:done` — is a live calculation over
  `completed_at` and `due_on`, so it never goes stale. The form, vehicle and
  assignee are denormalized from the schedule so "what's due for me" is a plain,
  join-free query.
  """
  use Ash.Resource,
    otp_app: :fleetms,
    domain: Fleetms.Inspections,
    data_layer: AshPostgres.DataLayer,
    authorizers: [Ash.Policy.Authorizer],
    extensions: [AshOban, AshJsonApi.Resource]

  import Fleetms.Permissions, only: [has_permission: 1]

  alias Fleetms.Inspections

  postgres do
    table "inspection_assignments"
    repo Fleetms.Repo

    references do
      reference :schedule, on_delete: :delete
      reference :vehicle, on_delete: :delete
      reference :inspection_form, on_delete: :delete
      reference :assigned_to, on_delete: :nilify
      # Keep the assignment if the inspection that completed it is deleted.
      reference :inspection, on_delete: :nilify
    end
  end

  oban do
    # Run scheduled actions once per organization. The tenant (an `org_<id>` schema
    # string) is what `Fleetms.Repo.all_tenants/0` returns and is set on the action.
    list_tenants fn -> Fleetms.Repo.all_tenants() end

    scheduled_actions do
      # Every morning, email each org's owner(s) a digest of overdue / due-soon
      # inspection assignments. Status is already correct without this — the job
      # only notifies.
      schedule :daily_due_digest, "0 7 * * *" do
        action :send_due_digest
        queue :inspection_digest
        worker_module_name Fleetms.Inspections.InspectionAssignment.Workers.DailyDueDigest
      end
    end
  end

  json_api do
    type "inspection-assignment"
  end

  actions do
    defaults [:read, :destroy]
    default_accept []

    read :get_by_id do
      get_by :id
      prepare build(load: [:status, vehicle: [:name], inspection_form: [:title]])
    end

    read :list do
      argument :schedule_id, :uuid
      argument :assigned_to_id, :uuid
      argument :only_open, :boolean, default: false

      argument :sort_by, :atom do
        constraints one_of: [:due_on, :completed_at, :inserted_at]
        default :due_on
      end

      argument :sort_order, :atom do
        constraints one_of: [:asc, :desc]
        default :asc
      end

      filter expr(
               if(is_nil(^arg(:schedule_id)), do: true, else: schedule_id == ^arg(:schedule_id)) and
                 if(is_nil(^arg(:assigned_to_id)),
                   do: true,
                   else: assigned_to_id == ^arg(:assigned_to_id)
                 ) and
                 if(^arg(:only_open), do: is_nil(completed_at), else: true)
             )

      pagination offset?: true, countable: true, default_limit: 20, max_page_size: 100

      prepare Fleetms.Inspections.InspectionAssignment.Preparations.ListInspectionAssignments
    end

    # Created by the schedule runner (system, actor-less).
    create :generate do
      primary? true

      accept [:due_on]

      argument :schedule_id, :uuid, allow_nil?: false
      argument :vehicle_id, :uuid, allow_nil?: false
      argument :inspection_form_id, :uuid, allow_nil?: false
      argument :assigned_to_id, :uuid

      change manage_relationship(:schedule_id, :schedule, type: :append_and_remove)
      change manage_relationship(:vehicle_id, :vehicle, type: :append_and_remove)

      change manage_relationship(:inspection_form_id, :inspection_form, type: :append_and_remove)

      change manage_relationship(:assigned_to_id, :assigned_to, type: :append_and_remove)
    end

    # Closed by the submit flow when a matching inspection is filled (system,
    # actor-less): stamp the completing inspection and the completion time.
    update :complete do
      require_atomic? false
      accept []

      argument :inspection_id, :uuid, allow_nil?: false

      change manage_relationship(:inspection_id, :inspection, type: :append_and_remove)
      change set_attribute(:completed_at, &DateTime.utc_now/0)
    end

    # Internal notifier action, invoked only by the AshOban scheduled job (no actor);
    # it reads with authorize?: false and only emails the org owner(s). Returns the
    # number of recipients emailed.
    action :send_due_digest, :integer do
      run fn _input, context ->
        Inspections.DueDigest.deliver_for_tenant(context.tenant)
      end
    end
  end

  policies do
    bypass actor_attribute_equals(:is_super_admin, true) do
      authorize_if always()
    end

    policy action_type(:read) do
      authorize_if has_permission(:view_inspection_schedules)
    end

    # Internal notifier action, invoked only by the AshOban scheduled job (no actor).
    policy action(:send_due_digest) do
      authorize_if always()
    end

    # `generate` and `complete` are system actions, only ever run actor-less
    # (authorize?: false) by the schedule runner and the submit flow.
  end

  multitenancy do
    strategy :context
  end

  attributes do
    uuid_primary_key :id

    attribute :due_on, :date do
      public? true
      allow_nil? false
      description "The date this inspection should be completed by."
    end

    attribute :completed_at, :utc_datetime do
      public? true
      writable? false
      description "When a matching inspection was submitted; nil while still open."
    end

    timestamps()
  end

  relationships do
    belongs_to :schedule, Fleetms.Inspections.InspectionSchedule do
      allow_nil? false
      public? true
      attribute_writable? true
    end

    belongs_to :vehicle, Fleetms.VehicleManagement.Vehicle do
      allow_nil? false
      public? true
      attribute_writable? true
    end

    belongs_to :inspection_form, Fleetms.Inspections.InspectionForm do
      allow_nil? false
      public? true
      attribute_writable? true
    end

    belongs_to :assigned_to, Fleetms.Accounts.User do
      domain Fleetms.Accounts
      allow_nil? true
      public? true
      attribute_writable? true
    end

    belongs_to :inspection, Fleetms.Inspections.Inspection do
      allow_nil? true
      public? true
      attribute_writable? true
      description "The submitted inspection that closed this assignment, if any."
    end
  end

  calculations do
    calculate :status,
              Inspections.AssignmentStatus,
              expr(
                cond do
                  not is_nil(completed_at) -> :done
                  due_on < fragment("CURRENT_DATE") -> :overdue
                  true -> :pending
                end
              )
  end
end
